from odoo import api, models


class IrModuleModule(models.Model):
    _inherit = 'ir.module.module'

    @api.model
    def get_global_module(self):
        """ Returns the global module gathering all customizations done in
            global (freshly created apps and customizations of existing apps).
            Creates that module if it doesn't exist yet.
        """
        global_module = self.search([('name', '=', 'global_customization')])
        if not global_module:
            global_module = self.create({
                'name': 'global_customization',
                'application': False,
                'category_id': self.env.ref('base.module_category_customizations_global').id,
                'shortdesc': 'Global customizations',
                'description': """This module has been generated by Odoo Global.
It contains the apps created with global and the customizations of existing apps.""",
                'state': 'installed',
                'imported': True,
                'author': self.env.company.name,
                'icon': '/base/static/description/icon.png',
                'license': 'OPL-1',
                'dependencies_id': [(0, 0, {'name': 'workflow_management'})],
            })
        return global_module
